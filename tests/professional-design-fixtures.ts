function text(
  ref: string,
  name: string,
  value: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fontSize: number,
  textColor = colors.ink,
): NativeVisualNode {
  return {
    ref,
    type: "TEXT",
    name,
    text: value,
    x,
    y,
    width,
    height,
    bounds: { x, y, width, height },
    visible: true,
    fontSize,
    textColor,
  };
}

